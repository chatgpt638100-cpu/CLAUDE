/// The occasions a template can be filed under (Screen 3 — "Category
/// filter as large horizontal pill tabs at top").
///
/// A fixed set rather than free-text tags: picking from five clear
/// occasions is a single tap, where inventing and remembering your own
/// labels is work. `other` is the escape hatch so nothing is unfileable.
enum TemplateCategory { wedding, birthday, holiday, anniversary, other }
